async function applyTranslations() {
  let connection;
  
  try {
    connection = await mysql.createConnection({
      host: process.env.DB_HOST || "localhost",
      user: process.env.DB_USER || "root",
      password: process.env.DB_PASSWORD || "",
      database: process.env.DB_NAME || "Information",
    });

    console.log("✓ 数据库连接成功\n");
    console.log(`✓ 翻译映射表包含 ${Object.keys(translationMap).length} 条翻译\n`);

    // 查询所有记录，然后在应用层过滤纯英文
    const [allRows] = await connection.query(
      `SELECT id, name FROM category_third ORDER BY id`
    );

    // 在JavaScript中过滤纯英文记录（不含中文字符）
    const rows = allRows.filter(row => {
      return !/[\u4e00-\u9fa5]/.test(row.name);
    });

    console.log(`查询到 ${allRows.length} 条总记录`);
    console.log(`其中纯英文记录: ${rows.length} 条\n`);
    
    console.log("开始批量翻译更新...\n");

    let updateCount = 0;
    let skipCount = 0;
    let foundCount = 0;

    for (const row of rows) {
      const translated = translationMap[row.name];
      
      if (translated && translated !== row.name) {
        foundCount++;
        if (foundCount <= 10) {
          console.log(`  找到翻译: "${row.name}" -> "${translated}"`);
        }
      }
      
      if (!translated || translated === row.name) {
        skipCount++;
        continue;
      }

      try {
        await connection.execute(
          "UPDATE category_third SET name = ? WHERE id = ?",
          [translated, row.id]
        );
        updateCount++;
        
        if (updateCount % 50 === 0) {
          console.log(`已更新 ${updateCount} 条...`);
        }
      } catch (error) {
        console.error(`✗ 更新 ID ${row.id} 失败: ${error.message}`);
      }
    }

    console.log("\n========================================");
    console.log("更新完成!");
    console.log("========================================");
    console.log(`成功更新: ${updateCount} 条`);
    console.log(`跳过: ${skipCount} 条`);

    // 验证结果
    const [chineseCount] = await connection.query(
      "SELECT COUNT(*) as count FROM category_third WHERE name REGEXP '[\\u4e00-\\u9fa5]'"
    );
    const [totalCount] = await connection.query(
      "SELECT COUNT(*) as count FROM category_third"
    );

    console.log(`\n当前状态:`);
    console.log(`总记录数: ${totalCount[0].count}`);
    console.log(`包含中文: ${chineseCount[0].count}`);
    console.log(`纯英文: ${totalCount[0].count - chineseCount[0].count}`);

  } catch (error) {
    console.error("\n❌ 错误:", error.message);
    throw error;
  } finally {
    if (connection) {
      await connection.end();
      console.log("\n✓ 数据库连接已关闭");
    }
  }
}

console.log("AI翻译工具 - 第一批");
